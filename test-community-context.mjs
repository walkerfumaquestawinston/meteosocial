import assert from 'node:assert/strict';
import {sameSkyTopic,communityForecast,postPlace} from './dist/community-context.js';
const weather=(code,extra={})=>({current:{weather_code:code,temperature_2m:22,time:new Date().toISOString().slice(0,19)},utc_offset_seconds:0,...extra});
assert.equal(sameSkyTopic(weather(61)),'Pioggia');
assert.equal(sameSkyTopic(weather(71)),'Neve');
assert.equal(sameSkyTopic(weather(0)),'Cielo sereno');
assert.equal(sameSkyTopic(weather(96)),null,'model thunderstorm is not a crowd hail observation');
assert.equal(sameSkyTopic(weather(3)),null,'clouds do not imply a clear sky');
assert.equal(sameSkyTopic(weather(61,{_offline:true})),null);
assert.equal(sameSkyTopic({current:{weather_code:61,time:'2020-01-01T00:00'}}),null);
assert.equal(sameSkyTopic({current:{weather_code:61}}),null);
assert.equal(communityForecast(null).temperature,'—');
assert.match(communityForecast(weather(61,{_offline:true})).source,/Dati salvati/);
const local=weather(61);local.current.time=new Date(Date.now()+7200000).toISOString().slice(0,19);local.utc_offset_seconds=7200;
assert.equal(sameSkyTopic(local),'Pioggia','uses the forecast location timezone, not device timezone');
assert.deepEqual(postPlace({city:'San Benedetto del Tronto',map_lat:4296,map_lon:1388}),{name:'San Benedetto del Tronto',latitude:42.96,longitude:13.88});
assert.deepEqual(postPlace({city:'Equatore',map_lat:0,map_lon:0}),{name:'Equatore',latitude:0,longitude:0});
assert.equal(postPlace({map_lat:null,map_lon:null}),null);
assert.equal(postPlace({map_lat:9001,map_lon:0}),null);
console.log('15 community-context checks passed');
