import assert from 'node:assert/strict';
import {insideViewport,weatherPoints,visibleSummary,isStorm,hailLabel,precipitationLabel,mapAIRequest} from './dist/map-weather-core.js';
const city=(name,latitude,longitude,t,mm=0,code=0)=>({name,latitude,longitude,current:{temperature_2m:t,precipitation:mm,weather_code:code,interval:900}});
const rome=city('Roma',41.9,12.5,24),milan=city('Milano',45.46,9.19,18,2,95),sydney=city('Sydney',-33.87,151.21,40);
const italy={west:6,east:19,south:35,north:48};
let s=visibleSummary([rome,milan,sydney],italy);
assert.equal(s.points.length,2);assert.equal(s.hot.name,'Roma');assert.equal(s.cold.name,'Milano');
assert.equal(s.rain.length,1);assert.equal(s.storms.length,1);
assert.equal(insideViewport(city('Fiji',-18,178,25),{west:170,east:-170,south:-30,north:0}),true);
assert.equal(insideViewport(city('Samoa',-14,-172,25),{west:170,east:190,south:-30,north:0}),true);
assert.equal(insideViewport(rome,{west:-540,east:540,south:-90,north:90}),true);
assert.equal(insideViewport({latitude:null,longitude:12},italy),false);
const towns=[['r','Roma','RM',41.902,12.501,100]],readings=new Map([['r',['r',23,0,0,4,5,900,'2026-09-21T09:00']]]);
const points=weatherPoints([rome,milan],towns,readings,null);
assert.equal(points.length,2);assert.equal(points[0].current.temperature_2m,23);assert.equal(points[0].current.interval,900);
assert.equal(visibleSummary(points,italy).rain.length,1,'rain data remains independent of selected temperature mode');
assert.equal(weatherPoints([rome],towns,readings,{...rome,current:{temperature_2m:null}}).length,1,'null is not zero');
assert.equal(isStorm(95),true);assert.equal(isStorm(96),true);assert.equal(isStorm(99),true);assert.equal(isStorm(80),false);assert.equal(isStorm(null),false);
assert.equal(hailLabel('2to4'),'Da 2 a 4 cm');assert.equal(hailLabel(null),'Dimensione non dichiarata');
assert.equal(precipitationLabel(900),'mm / 15 min');assert.match(precipitationLabel(null),/non disponibile/);
const request=mapAIRequest({...milan,author:'private',mediaURL:'private'},'Spiega','solo nella vista','pioggia');
assert.equal(request.city,'Milano');assert.equal(request.section,'map');assert.equal(request.includeCommunity,false);assert.equal(request.latitude,milan.latitude);
assert.equal(JSON.stringify(request).includes('private'),false);
assert.throws(()=>mapAIRequest({name:'Senza punto'},'x','y'));
assert.ok(mapAIRequest(rome,'x'.repeat(3000),'s'.repeat(3000)).question.length<1500);
console.log('31 checks: visible bounds, antimeridian, deduplication, rain independence, hail units, model storms, AI transport allowlist');
