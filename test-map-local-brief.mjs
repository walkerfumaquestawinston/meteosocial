import assert from 'node:assert/strict';
import {localBrief,briefMarkup,changeMarkup} from './dist/map-local-brief.js';
const now=new Date('2026-09-22T10:00:00Z');
const current={time:'2026-09-22T19:00',weather_code:0,temperature_2m:0,precipitation:0,wind_speed_10m:0,interval:900};
const w={timezone:'Asia/Tokyo',current};
assert.equal(localBrief(w,'ok',now).status,'ready','use city timezone, not device timezone');
assert.equal(localBrief(w,'ok',now).temperature,'0°');
assert.equal(localBrief(w,'ok',now).rain,'0 mm');
assert.equal(localBrief(w,'ok',now).wind,'0 km/h');
assert.equal(localBrief(w,'ok',now).interval,'Precip. / 15 min');
assert.equal(localBrief({...w,_offline:true},'ok',now).status,'stale');
assert.equal(localBrief({...w,_provenance:{capturedAt:+now-91*60000}},'ok',now).status,'stale');
assert.equal(localBrief({...w,timezone:'invalid'},'ok',now).status,'stale');
assert.equal(localBrief(w,'error',now).status,'error');
assert.equal(localBrief(null,'loading',now).status,'loading');
assert.equal(localBrief(null,'error',now).temperature,'—');
const missing=localBrief({...w,current:{...current,temperature_2m:null,precipitation:-1,wind_speed_10m:NaN,weather_code:null}},'ok',now);
assert.equal(missing.temperature,'—');assert.equal(missing.rain,'—');assert.equal(missing.wind,'—');
assert.equal(missing.condition,'Condizione non disponibile');
assert.equal(localBrief({...w,current:{...current,time:'2026-09-22T20:00'}},'ok',now).status,'stale');
assert.match(localBrief({...w,current:{...current,time:'2026-09-21T19:00'}},'ok',now).time,/21\/09/);
assert.match(localBrief({...w,current:{...current,time:'2026-09-22T25:66'}},'ok',now).time,/—/);
assert.ok(!briefMarkup({name:'<img src=x onerror=alert(1)>'},null,'loading').includes('<img'));
assert.equal(changeMarkup(w,'error'),'');assert.equal(changeMarkup(w,'loading'),'');
assert.match(changeMarkup(null,'ok'),/Aspettiamo/);
console.log('Local map brief: city timezone, zero/missing values, offline/old/error/future timestamps and escaped content passed.');
