import assert from 'node:assert/strict';
import {elapsedLabel,checkStatus,sourceStatus} from './dist/map-live-status.js';
const now=Date.parse('2026-09-22T10:00:00Z');
assert.equal(elapsedLabel(now-59000,now),'59 s fa');
assert.equal(elapsedLabel(now-61000,now),'1 min 01 s fa');
assert.equal(elapsedLabel(now-3661000,now),'1 h 1 min fa');
assert.match(elapsedLabel(null,now),/non disponibile/);
assert.match(elapsedLabel(now+60000,now),/futuro/);
assert.equal(checkStatus({checkedAt:now,failed:true,now}).tone,'warning');
assert.match(checkStatus({checkedAt:now,failed:true,now}).label,/incompleto/);
assert.match(checkStatus({checkedAt:now,checking:true,offline:true,now}).label,/offline/);
assert.match(checkStatus({checkedAt:now,outdated:true,now}).label,/precedente/);
assert.match(checkStatus({checkedAt:now,checking:true,now}).label,/fonti/);
assert.match(checkStatus({now}).label,/attesa/);
const current={time:'2026-09-22T09:45'};
const first=sourceStatus({checkedAt:now,current,now});
assert.equal(sourceStatus({checkedAt:now+60000,current,now:now+60000}).model,first.model,'checking again never changes model validity time');
assert.equal(current.time,'2026-09-22T09:45');
console.log('Live clock: second boundaries, absent/future times, offline/loading/errors and immutable data timestamps passed.');
