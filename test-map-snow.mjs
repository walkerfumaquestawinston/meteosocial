import assert from 'node:assert/strict';
import {snowReading,weatherPoints,visibleSummary} from './dist/map-weather-core.js';
import {FIELD_MODES,fieldHours,hourQuestion} from './dist/map-field-core.js';
import {sourceStatus,MAP_REFRESH_MS} from './dist/map-live-status.js';
assert.equal(MAP_REFRESH_MS,60000);
assert.equal(snowReading({snowfall:0,weather_code:0}).indicated,false);
assert.equal(snowReading({snowfall:.4,weather_code:71}).amount,.4);
assert.deepEqual(snowReading({snowfall:null,weather_code:85}),{amount:null,indicated:true});
assert.equal(snowReading({weather_code:0}),null);
assert.equal(snowReading({snowfall:-1,weather_code:0}),null);
const points=weatherPoints([],[['x','Città','AA',45,10]],new Map([['x',['x',-2,1,73,8,10,900,'2026-09-22T10:00',.7]]]),null);
assert.equal(points[0].current.snowfall,.7);assert.equal(visibleSummary(points,{west:0,east:20,south:40,north:50}).snow.length,1);
const now=Date.parse('2026-09-22T10:15:00Z');
const w={timezone:'UTC',hourly:{time:['2026-09-22T11:00','2026-09-22T12:00'],snowfall:[.8,null],snow_depth:[.12,null],freezing_level_height:[1400,null],visibility:[2000,null]}};
const hours=fieldHours(w,now);assert.equal(hours[0].snowfall,.8);assert.equal(hours[0].snow_depth,.12);assert.equal(hours[0].freezing_level_height,1400);assert.equal(hours[1].snowfall,null);
assert.equal(FIELD_MODES.neve.field,'snowfall');assert.match(hourQuestion(hours[0]),/neve fresca 0.8 cm/);
let s=sourceStatus({checkedAt:now,current:{time:'2026-09-22T10:00'},radar:{enabled:true,time:(now-40*60000)/1000},now});assert.equal(s.stale,false);assert.match(s.radar,/precedente/);
s=sourceStatus({checkedAt:now,current:{time:'2026-09-21T10:00'},now});assert.equal(s.stale,true);assert.match(s.model,/precedente/);
assert.equal(sourceStatus({current:{time:'invalid'},now}).stale,true);assert.match(sourceStatus({now}).model,/non disponibile/);
console.log('Snow amounts, missing values, town samples, hourly units and separate source clocks passed.');
