import assert from 'node:assert/strict';
import {createNearby} from './dist/nearby.js';
const buttons=['all','car','people'].map(kind=>({dataset:{nearKind:kind},setAttribute(){}}));
globalThis.document={querySelector:s=>s==='#nearby-panel'?{}:null,querySelectorAll:s=>s==='[data-near-kind]'?buttons:[]};
globalThis.fetch=async()=>{throw Error('Radar unavailable in this isolated test')};
let place={name:'Roma',latitude:41.9,longitude:12.5},pending=[];
const app=createNearby({get:()=>({place,weather:null}),api:path=>new Promise(resolve=>pending.push({path,resolve})),render(){}});
const flush=()=>new Promise(resolve=>setTimeout(resolve,0));
const payload=(name,type)=>({places:[{id:name,name,type,lat:place.latitude,lon:place.longitude,source:'Community',fee:'Da verificare'}]});
app.bind();assert.equal(pending.length,1);
buttons[2].onclick();assert.equal(pending.length,2,'changing type must launch the new request while the old one is pending');
assert.match(pending[1].path,/category=people/);
pending[1].resolve(payload('Biblioteca aggiornata','people'));await flush();
pending[0].resolve(payload('Parcheggio obsoleto','car'));await flush();
assert.match(app.page(),/Biblioteca aggiornata/,'late old request must not replace new results');
assert.doesNotMatch(app.page(),/Parcheggio obsoleto/);
buttons[1].onclick();const previous=pending[2];
place={name:'Milano',latitude:45.46,longitude:9.19};app.bind();assert.equal(pending.length,4,'city change launches a fresh request');
pending[3].resolve(payload('Garage Milano','car'));await flush();previous.resolve(payload('Garage Roma ritardato','car'));await flush();
assert.match(app.page(),/Garage Milano/);assert.doesNotMatch(app.page(),/Garage Roma ritardato/);
app.dispose();console.log('8 nearby state checks passed');
