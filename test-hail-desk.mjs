import assert from 'node:assert/strict';
import {hailSelection,hailEvidence} from './dist/map-field-core.js';
const now=Date.parse('2026-09-22T12:00:00Z'),center={latitude:42,longitude:13};
const report=(id,minutes,extra={})=>({id,...center,observed:now-minutes*60000,expires:now+60000,...extra});
const data=[report('new',2,{latitude:42.1}),report('old',45),report('ended',3,{ended:now-60000}),report('future',-1),report('expired',1,{expires:now}),report('boundary',120),report('invalid',1,{latitude:400})];
assert.deepEqual(hailSelection(data,center,{minutes:15,now}).map(p=>p.id),['ended','new']);
assert.deepEqual(hailSelection(data,center,{minutes:15,includeEnded:false,now}).map(p=>p.id),['new']);
assert.deepEqual(hailSelection(data,center,{sort:'recent',now}).map(p=>p.id),['new','ended','old']);
assert.equal(hailSelection(data,center,{minutes:15,radius:5,includeEnded:false,now}).length,0);
assert.equal(hailSelection([report('exact',15)],center,{minutes:15,now}).length,0);
assert.equal(hailSelection([report('duplicate',1),report('duplicate',1)],center,{now}).length,1);
assert.equal(hailSelection(null,center,{now}).length,0);
assert.equal(hailSelection(data,{latitude:NaN,longitude:0},{now}).length,0);
assert.equal(hailSelection(data,center,{minutes:0,now}).length,0);
assert.equal(hailSelection([report('seam',1,{latitude:0,longitude:-179.9})],{latitude:0,longitude:179.9},{radius:25,now}).length,1);
const before=JSON.stringify(data);hailSelection(data,center,{sort:'recent',now});assert.equal(JSON.stringify(data),before);
assert.equal(hailEvidence([],{state:'loading',now}).tone,'pending');
assert.equal(hailEvidence([],{state:'error',now}).tone,'unknown');
assert.equal(hailEvidence([],{state:'ok',updatedAt:now-300000,now}).tone,'unknown');
assert.equal(hailEvidence([],{state:'ok',updatedAt:now,now}).tone,'empty');
assert.match(hailEvidence([],{state:'ok',updatedAt:now,now}).detail,/n.esclut|non esclude/);
assert.equal(hailEvidence([report('ended',2,{ended:1})],{state:'ok',updatedAt:now,now}).active,0);
assert.equal(hailEvidence([report('active',2)],{state:'ok',updatedAt:now,now}).tone,'reported');
console.log('Grandine: 18 verifiche superate (tempo, distanza, cessazione, scadenza, dati mancanti, antimeridiano e freschezza).');
